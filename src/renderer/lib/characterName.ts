/**
 * 判断一个名字是否像真实角色名
 * - 非空、长度 ≤ 12
 * - 不在黑名单中
 * - 不含纯数字/特殊符号
 * - 不是引号包裹
 * - 单字虚词排除
 */
export function looksLikeCharacterName(name: string): boolean {
  const trimmed = name.trim()
  if (!trimmed || trimmed.length > 12) return false
  if (NON_CHARACTER_NAMES.has(trimmed)) return false
  // 纯数字 / 含特殊符号 → 不是角色名
  if (/^[\d\s\-+*#=()（）]+$/.test(trimmed)) return false
  // 以引号/括号包裹的 → 不是角色名
  if (/^[「」『』""''《》【】\[\]]+$/.test(trimmed)) return false
  // 单字且是常见虚词/量词
  if (trimmed.length === 1 && /^[的是有了在把被对从向和与或而但如因所于]$/.test(trimmed)) return false
  // XX道 模式：以"道"结尾的 2 字词大概率是流派/属性名而非人名
  if (/^.{1,3}道$/.test(trimmed) && trimmed.length <= 4) return false
  return true
}
